import { Column, CreateDateColumn, Entity, PrimaryGeneratedColumn } from 'typeorm';

import { numeric } from '../common/db.js';

export const TX_TYPES = ['deposit', 'withdrawal', 'stake_lock', 'stake_release', 'penalty', 'reward', 'donation'] as const;
export type TxType = (typeof TX_TYPES)[number];
export const TX_METHODS = ['crypto', 'fiat', 'internal'] as const;
export type TxMethod = (typeof TX_METHODS)[number];
export type TxStatus = 'pending' | 'confirmed' | 'failed';

@Entity('wallet_transactions')
export class WalletTransaction {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column('uuid')
  userId: string;

  @Column({ type: 'uuid', nullable: true })
  goalId: string | null;

  @Column({ type: 'enum', enum: TX_TYPES, enumName: 'tx_type' })
  type: TxType;

  @Column({ type: 'enum', enum: TX_METHODS, enumName: 'tx_method' })
  method: TxMethod;

  @Column({ type: 'numeric', transformer: numeric })
  amount: number;

  @Column({ type: 'varchar' })
  currency: string;

  @Column({ type: 'enum', enum: ['pending', 'confirmed', 'failed'], enumName: 'tx_status' })
  status: TxStatus;

  @Column({ type: 'varchar', nullable: true })
  chain: string | null;

  @Column({ type: 'varchar', nullable: true })
  txHash: string | null;

  // Generated by the database (voucher code shown to the user).
  @Column({ type: 'varchar', insert: false, update: false })
  referenceCode: string;

  @Column({ type: 'varchar', nullable: true })
  note: string | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;

  @Column({ type: 'timestamptz', nullable: true })
  confirmedAt: Date | null;
}
